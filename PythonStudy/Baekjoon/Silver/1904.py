# 01 타일, 각각의 타일들은 0또는 1이 쓰여 있는 낱장의 타일들
# 현재 타일은 00과 1로, 0은 모두 00으로 붙어있고, 1은 낱장
# N = 1 -> 1(1), N = 2 -> 11, 00(2) N = 3 -> 100, 001, 111(3)
# N = 4 -> 0000, 0011, 1001, 1100, 1111(5) 
# N = 5 -> 00001, 00100, 10000, 11100, 00111, 10011, 11001, 11111(8)
# 1, 2, 3, 5, 8 ... -> 피보나치, A[N] = A[N-2] + A[N-1]

N = int(input())
a = [0] * (N + 1)
a[1] = 1
if N > 1:
    a[2] = 2
for i in range(3, N+1):
    a[i] = (a[i-1] + a[i-2]) % 15746

print(a[N])
